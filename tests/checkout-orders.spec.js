import { test, expect } from '@playwright/test';
const base = process.env.SITE_URL || 'http://localhost:5173';
test('demo checkout, browser-private history and authenticated admin fulfillment', async ({ page, browser }) => {
  test.skip(!process.env.TEST_ADMIN_KEY, 'Requires local API and TEST_ADMIN_KEY; never run against a live store.');
  await page.goto(base);
  await page.getByRole('button', { name: /Add The Everyday Favorite to basket/ }).click();
  await page.getByRole('button', { name: 'Open basket' }).click();
  await page.getByRole('button', { name: 'Try demo checkout' }).click();
  await expect(page.locator('#checkout-submit')).toBeEnabled();
  for (const [name, value] of Object.entries({ name: 'Demo Customer', email: 'demo@example.com', line1: '123 Test Street', city: 'Test City', state: 'Test State', postalCode: '110001' })) await page.locator(`#checkout-form [name=${name}]`).fill(value);
  await page.getByRole('button', { name: 'Create demo order' }).click();
  await expect(page.locator('#checkout-status')).toContainText('No payment was taken');
  await page.getByRole('link', { name: 'View order status' }).click();
  await expect(page.locator('article')).toHaveCount(1);
  await expect(page.locator('article')).toContainText('Demo confirmation only');
  const other = await browser.newContext(); const outsider = await other.newPage();
  await outsider.goto(`${base}/orders.html`);
  await expect(outsider.locator('#status')).toContainText('Start a checkout session first');
  await other.close();
  await page.goto(`${base}/admin.html`);
  await expect(page.locator('#status')).toContainText('Administrator authentication required');
  await page.getByLabel('Administrator access key').fill(process.env.TEST_ADMIN_KEY);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await expect(page.locator('#login')).toBeHidden();
  await page.locator('article').first().getByLabel('Fulfillment status').selectOption('processing');
  await page.locator('article').first().getByRole('button', { name: 'Update order' }).click();
  await expect(page.locator('article').first()).toContainText('Fulfillment: processing');
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page.locator('#orders')).toBeEmpty();
  await page.setViewportSize({ width: 320, height: 720 });
  await page.goto(`${base}/orders.html`);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
